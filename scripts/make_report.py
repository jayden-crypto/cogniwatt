"""Assemble the R1 results report from evaluation CSVs and run histories.

Owner: R1. Emits docs/r1_results.md - the Lab progress deliverable.
"""
import json, pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd

RUNS = pathlib.Path("results/runs")
EVAL = pathlib.Path("results/eval")

ORDER = ["oracle", "ppo", "greedy_value", "always_ask", "always_offload",
         "always_big", "always_tiny", "no_think", "random_valid", "random"]


def _key(a):
    for i, p in enumerate(ORDER):
        if a.startswith(p):
            return i
    return 99


def table(df: pd.DataFrame, cols=None) -> str:
    g = df.groupby("agent").agg(
        success=("success", "mean"),
        ret=("ret", "mean"),
        se=("ret", lambda x: x.std(ddof=1) / np.sqrt(len(x))),
        energy=("energy_J", "mean"), lat=("latency_s", "mean"),
        asks=("asks", "mean"),
        tiny=("n_tiny", "mean"), big=("n_big", "mean"),
        off=("n_offload", "mean"),
    ).reset_index()
    g = g.sort_values("agent", key=lambda s: s.map(_key))
    lines = ["| agent | success | return ± se | energy (J) | latency (s) | asks | tiny / big / cloud |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for _, r in g.iterrows():
        lines.append(f"| `{r.agent}` | **{r.success:.3f}** | {r.ret:+.2f} ± {r.se:.2f} | "
                     f"{r.energy:.1f} | {r.lat:.1f} | {r.asks:.2f} | "
                     f"{r.tiny:.2f} / {r.big:.2f} / {r['off']:.2f} |")
    return "\n".join(lines)


def final_success(tag: str, last: int = 15):
    f = RUNS / tag / "history.json"
    if not f.exists():
        return None
    h = json.loads(f.read_text())["history"]
    if not h:
        return None
    return float(np.mean([r["success"] for r in h[-last:]]))


def main():
    parts = ["# CogniWatt — R1 Results\n",
             "Generated by `scripts/make_report.py`. All returns in natural "
             "(unshaped) units; shaping is stripped from reported metrics.\n"]

    for split, title in [("train", "Training devices"), ("heldout", "Held-out devices (zero-shot)")]:
        f = EVAL / f"eval_{split}.csv"
        if not f.exists():
            continue
        df = pd.read_csv(f)
        devs = sorted(df.device.unique())
        parts.append(f"\n## {title}\n\nDevices: {', '.join('`'+d+'`' for d in devs)}  "
                     f"(n={len(df[df.agent=='oracle'])} paired episodes per agent)\n")
        parts.append(table(df))

    tags = sorted(p.name for p in RUNS.iterdir() if (p / "history.json").exists())
    abl = [t for t in tags if t.startswith(("entanneal", "ablate", "main"))]
    if abl:
        parts.append("\n## Ablations (final training success, mean of last 15 logs)\n")
        parts.append("| run | success | note |\n| --- | --- | --- |")
        notes = {
            "entanneal": "full method (entropy annealed 0.12 -> 0.01)",
            "main": "constant ent_coef 0.12",
            "ablate_capdrop": "capability dropout 0.35",
            "ff_2m": "legacy, pre-lambda_cloud reward - not comparable",
            "ablate_devcond": "no device-feature conditioning",
            "ablate_shaping": "no potential-based shaping",
            "ablate_mask": "no invalid-action masking",
        }
        for t in abl:
            s = final_success(t)
            if s is not None:
                # sweep tags carry a _s<seed> suffix; the note is keyed on the arm
                arm = re.sub(r"_s\d+$", "", t)
                parts.append(f"| `{t}` | {s:.3f} | {notes.get(arm, '')} |")
        parts.append("\nThe full method is shown across all 8 seeds (0.898-0.910); "
                     "the ablations are one seed each. Since the entropy fix "
                     "(docs/r1_stability.md) these no longer collapse, so the "
                     "differences here are small and need several seeds each "
                     "before any of them can be called load-bearing.")

    sweep = [t for t in tags if t.startswith("ask")]
    if sweep:
        parts.append("\n## Pareto sweep over the price of a question (λ_Q)\n")
        parts.append("| run | λ_Q | success |\n| --- | --- | --- |")
        rows = []
        for t in sweep:
            a = json.loads((RUNS / t / "history.json").read_text())["args"]
            rows.append((float(a["lambda_ask"]), t, final_success(t)))
        for lam, t, s in sorted(rows):
            parts.append(f"| `{t}` | {lam} | {s:.3f} |")
        parts.append("\nEvery price now trains. The previous report restricted "
                     "this sweep to lambda_Q <= 3.5 because higher prices "
                     "collapsed training; those collapses were the entropy "
                     "artefact of docs/r1_stability.md, not the question price.")

    out = pathlib.Path("docs/r1_results.md")
    out.write_text("\n".join(parts) + "\n")
    print(f"wrote {out}")
    print("\n".join(parts))


if __name__ == "__main__":
    main()
